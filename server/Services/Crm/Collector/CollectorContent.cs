    /// <summary>
    /// One row of the Cosmetic crate's content table (docs/design/economy-collector.md §2.3, §3.4): what its
    /// <c>Id@Type</c>/<c>Id@Subtype</c>/<c>Id@Subtype2</c>/<c>Id@BundledRewards</c> cells say, and which item of the
    /// player's inventory its weight counts (<see cref="Merc"/>, <see cref="Item"/>).
    /// </summary>
    public sealed class CollectorRow
    {
        public int Id;
        public string Category;
        public string Type;
        public string Subtype;

        /// <summary>null when the row has none ("–" in §2.3: the cell is not sent).</summary>
        public string Subtype2;

        /// <summary>A carrier's <c>KillSignature_Sound_&lt;n&gt;</c> (D8); null otherwise.</summary>
        public string Bundle;

        /// <summary>The agent of a skin or agent row.</summary>
        public int? Merc;

        /// <summary>The sound, skin or hidden jersey id of the row.</summary>
        public int? Item;
    }

    /// <summary>
    /// server/Content/collector.json (generated by tools/content-gen <c>build_collector</c>; a file of the same name in
    /// &lt;data&gt;/content/ overrides it): the crate, its rows and the id sets the CRM cells and weights need
    /// (economy-collector.md §3.4). Ids only, no game text. <see cref="Parse(string, Log)"/> refuses a file that is broken,
    /// that breaks the preview-safety rule of §2.3.1 or whose crate or table is not the guard's <c>Crate_Event_Special</c>
    /// (<see cref="CollectorGuard"/>): the collector then stays inactive (the guard, §2.12).
    /// </summary>
    public sealed class CollectorContent
    {
        public const string FileName = "collector.json";

        /// <summary>The <c>format</c> this server reads (content-gen <c>FORMAT</c>).</summary>
        public const int Format = 1;

        /// <summary>The client's content tables have 100 rows; only existing rows can change (EN/Database.cs:143-196).</summary>
        public const int MaxRows = 100;

        public const string Avatars = "avatars";
        public const string Backgrounds = "backgrounds";
        public const string Sounds = "sounds";
        public const string Skins = "skins";
        public const string HiddenJerseys = "hiddenJerseys";
        public const string Agents = "agents";
        public const string Camos = "camos";
        public const string Jerseys = "jerseys";
        public const string Exhausted = "exhausted";

        /// <summary>The no-source tier (§4.1 <c>base</c>).</summary>
        public static readonly string[] BaseCategories = { Avatars, Backgrounds, Sounds, Skins, HiddenJerseys, Agents };

        /// <summary>The VIP pools (§4.1 <c>paid</c>).</summary>
        public static readonly string[] PaidCategories = { Camos, Jerseys };

        private const string SoundBundlePrefix = "KillSignature_Sound_";
        private const int MaxIds = 100000;

        public string CrateId;
        public string Table;
        public string LocId;
        public string Image;
        public List<CollectorRow> Rows = new List<CollectorRow>();

        // Avatar sets (§1.2, §1.3), ascending.
        public List<int> AvatarsBase = new List<int>();
        public List<int> AvatarsDrawable = new List<int>();
        public List<int> AvatarsUnlock = new List<int>();
        public List<int> AvatarsLock = new List<int>();
        public List<int> AvatarsKayac = new List<int>();
        public List<int> AvatarsReserved = new List<int>();

        // Backgrounds (§1.4), ascending.
        public List<int> BackgroundsBase = new List<int>();
        public List<int> BackgroundsDrawable = new List<int>();
        public List<int> BackgroundsUnlock = new List<int>();

        public List<int> SoundIds = new List<int>();

        /// <summary>The camo pool of every agent the crate knows (§1.5), by agent id; its keys are the agents.</summary>
        public Dictionary<int, List<int>> CamoPools = new Dictionary<int, List<int>>();

        /// <summary>The visible non-Kayac jerseys, the same pool for every agent.</summary>
        public List<int> JerseyPool = new List<int>();

        // Season (§2.4, §2.5).
        public List<string> Tiers = new List<string>();
        public List<int> DivisionTier = new List<int>();
        public List<string[]> Retarget = new List<string[]>();
        public List<string[]> Placement = new List<string[]>();

        /// <summary>Numerals I..XII in order, each [no star, ★, ★★, ★★★].</summary>
        public List<int[]> Emblems = new List<int[]>();

        public List<int> Levels = new List<int>();

        /// <summary>The source text's hash.</summary>
        public string Hash = "";

        /// <summary>The agents, ascending (the keys of the camo pools: every agent of the game).</summary>
        public List<int> AgentIds
        {
            get
            {
                var ids = new List<int>(CamoPools.Keys);
                ids.Sort((a, b) => a.CompareTo(b));
                return ids;
            }
        }

        public static bool IsBaseCategory(string category)
        {
            return Array.IndexOf(BaseCategories, category) >= 0;
        }

        public static bool IsPaidCategory(string category)
        {
            return Array.IndexOf(PaidCategories, category) >= 0;
        }

        /// <summary>The parsed file, or null with the problem logged as an error (the collector stays inactive).</summary>
        public static CollectorContent Parse(string text, Log log)
        {
            string problem;
            CollectorContent content = Parse(text, out problem);
            if (content == null && log != null) log.Error(FileName + " refused: " + problem + "; the collector stays inactive (guard only)");
            return content;
        }

        /// <summary>The parsed file, or null and why. Never throws.</summary>
        public static CollectorContent Parse(string text, out string problem)
        {
            problem = null;
            object parsed;
            if (string.IsNullOrEmpty(text) || !MiniJson.TryParse(text, out parsed) || !(parsed is Dictionary<string, object>))
            {
                problem = "not a JSON object";
                return null;
            }
            try
            {
                CollectorContent content = Read((Dictionary<string, object>)parsed);
                content.Hash = LiveOpsHash.Hex(text);
                return content;
            }
            catch (Refused ex)
            {
                problem = ex.Message;
                return null;
            }
        }

        /// <summary>
        /// Why a row may not carry <c>Weight#1 &gt; 0</c>, or null (the preview-safety rule, §2.3.1): <c>GetPreview</c>
        /// keys every weighted row on its image, so only these rewards may be drawn: <c>KillSignature/Avatar|Background/Random</c>,
        /// <c>MercSkin/&lt;m&gt;/&lt;s&gt;</c>, <c>MercAccessory/Random/&lt;id|Random&gt;</c>, <c>UnlockMerc/&lt;id&gt;</c>,
        /// <c>WeaponCamo/Random/Random</c>, <c>VersusCoins/Tiers&lt;n&gt;</c>; sounds only as the bundle of a
        /// <c>KillSignature/Avatar/Random</c> carrier (D8). The same rule as content-gen <c>collector_row_problem</c>.
        /// </summary>
        public static string RowProblem(string type, string subtype, string subtype2, string bundle)
        {
            bool ok;
            switch (type)
            {
                case "KillSignature":
                    ok = (subtype == "Avatar" || subtype == "Background") && subtype2 == "Random";
                    break;
                case "MercSkin":
                    ok = IsDigits(subtype) && IsDigits(subtype2);
                    break;
                case "MercAccessory":
                    ok = subtype == "Random" && (subtype2 == "Random" || IsDigits(subtype2));
                    break;
                case "UnlockMerc":
                    ok = IsDigits(subtype) && subtype2 == null;
                    break;
                case "WeaponCamo":
                    ok = subtype == "Random" && subtype2 == "Random";
                    break;
                case "VersusCoins":
                    ok = IsTier(subtype) && subtype2 == null;
                    break;
                default:
                    ok = false;
                    break;
            }
            if (!ok) return Describe(type) + "/" + Describe(subtype) + "/" + Describe(subtype2) + " cannot be previewed with weight";
            if (bundle != null)
            {
                if (!bundle.StartsWith(SoundBundlePrefix, StringComparison.Ordinal) || !IsDigits(bundle.Substring(SoundBundlePrefix.Length)))
                    return "bundle " + bundle + " is not a " + SoundBundlePrefix + "<n> carrier bundle";
                if (type != "KillSignature" || subtype != "Avatar" || subtype2 != "Random")
                    return "bundle " + bundle + " on a non-carrier " + type + "/" + subtype + "/" + Describe(subtype2)
                           + " row (only KillSignature/Avatar/Random rows carry sounds)";
            }
            return null;
        }

        /// <summary>"Tiers&lt;n&gt;": a currency tier row (VersusCoinsTiers).</summary>
        public static bool IsTier(string subtype)
        {
            return subtype != null && subtype.StartsWith("Tiers", StringComparison.Ordinal) && IsDigits(subtype.Substring(5));
        }

        /// <summary>"2,4-6,9" → [2, 4, 5, 6, 9] (content-gen <c>compress_ranges</c>); "" → []. Null when malformed.</summary>
        public static List<int> ExpandRanges(string text)
        {
            var ids = new List<int>();
            if (text == null) return null;
            if (text.Length == 0) return ids;
            foreach (string part in text.Split(','))
            {
                int dash = part.IndexOf('-');
                int first, last;
                if (dash < 0)
                {
                    if (!TryId(part, out first)) return null;
                    last = first;
                }
                else if (!TryId(part.Substring(0, dash), out first) || !TryId(part.Substring(dash + 1), out last) || last < first)
                {
                    return null;
                }
                if (ids.Count + (long)(last - first) + 1 > MaxIds) return null;
                for (int i = first; i <= last; i++) ids.Add(i);
            }
            ids.Sort((a, b) => a.CompareTo(b));
            for (int i = 1; i < ids.Count; i++)
                if (ids[i] == ids[i - 1]) return null;
            return ids;
        }

        // ------------------------------------------------------------------------------------------ reading

        private static CollectorContent Read(Dictionary<string, object> root)
        {
            var c = new CollectorContent();
            long? format = JsonValue.AsLong(JsonValue.Get(root, "format"));
            if (format != Format)
                throw new Refused("format " + (format.HasValue ? format.Value.ToString(CultureInfo.InvariantCulture) : "missing")
                                  + " is not " + Format.ToString(CultureInfo.InvariantCulture) + " (regenerate it with tools/content-gen)");

            var crate = RequiredObject(root, "crate");
            c.CrateId = Required(crate, "crate.id");
            c.Table = Required(crate, "crate.table");
            // Live ops hand out Crate_Event_Special and only it has the guard (§2.8, §2.12, O1). A layer on another crate
            // or table would leave the handed-out crate's content table empty (it throws on claim, §0.3.6) and rewrite a
            // shipped crate.
            if (c.CrateId != CollectorGuard.CrateId)
                throw new Refused("crate.id " + c.CrateId + " is not " + CollectorGuard.CrateId + " (the crate live ops hand out and the guard covers)");
            if (c.Table != CollectorGuard.CrateTable)
                throw new Refused("crate.table " + c.Table + " is not " + CollectorGuard.CrateTable + " (the content table the guard covers)");
            c.LocId = Required(crate, "crate.locId");
            c.Image = Required(crate, "crate.image");

            List<object> rows = JsonValue.GetArray(root, "rows");
            if (rows == null || rows.Count == 0 || rows.Count > MaxRows)
                throw new Refused("rows must hold 1.." + MaxRows.ToString(CultureInfo.InvariantCulture) + " rows");
            int exhausted = 0;
            foreach (object item in rows)
            {
                CollectorRow row = ReadRow(item as Dictionary<string, object>, c.Rows.Count + 1);
                if (row.Category == Exhausted) exhausted++;
                c.Rows.Add(row);
            }
            // Without it an unlock-all profile would get a crate whose every weight is 0.
            if (exhausted != 1) throw new Refused("rows must hold exactly one exhausted row (it has " + exhausted.ToString(CultureInfo.InvariantCulture) + ")");

            var avatars = RequiredObject(root, "avatars");
            c.AvatarsBase = Ranges(avatars, "base", "avatars");
            c.AvatarsDrawable = Ranges(avatars, "drawable", "avatars");
            c.AvatarsUnlock = Ranges(avatars, "unlock", "avatars");
            c.AvatarsLock = Ranges(avatars, "lock", "avatars");
            c.AvatarsKayac = Ranges(avatars, "kayac", "avatars");
            c.AvatarsReserved = Ranges(avatars, "reserved", "avatars");
            var backgrounds = RequiredObject(root, "backgrounds");
            c.BackgroundsBase = Ranges(backgrounds, "base", "backgrounds");
            c.BackgroundsDrawable = Ranges(backgrounds, "drawable", "backgrounds");
            c.BackgroundsUnlock = Ranges(backgrounds, "unlock", "backgrounds");
            c.SoundIds = Ids(JsonValue.GetArray(root, "sounds"), "sounds");

            var camos = RequiredObject(root, "camos");
            foreach (var kv in camos)
            {
                int agent;
                if (!TryId(kv.Key, out agent)) throw new Refused("camos: '" + kv.Key + "' is not an agent id");
                List<int> pool = ExpandRanges(JsonValue.AsString(kv.Value));
                if (pool == null) throw new Refused("camos." + kv.Key + " is not a list of id ranges");
                c.CamoPools[agent] = pool;
            }
            if (c.CamoPools.Count == 0) throw new Refused("camos names no agent");
            c.JerseyPool = ExpandRanges(JsonValue.GetString(root, "jerseys"));
            if (c.JerseyPool == null) throw new Refused("jerseys is not a list of id ranges");

            ReadSeason(c, RequiredObject(root, "season"));
            c.Levels = ExpandRanges(JsonValue.GetString(root, "levels"));
            if (c.Levels == null) throw new Refused("levels is not a list of id ranges");

            Check(c);
            return c;
        }

        private static CollectorRow ReadRow(Dictionary<string, object> o, int expectedId)
        {
            string at = "row " + expectedId.ToString(CultureInfo.InvariantCulture);
            if (o == null) throw new Refused(at + " is not an object");
            long? id = JsonValue.AsLong(JsonValue.Get(o, "id"));
            if (id != expectedId) throw new Refused(at + ": ids must run 1..n");
            var row = new CollectorRow
            {
                Id = expectedId,
                Category = Required(o, at + ".category", "category"),
                Type = Required(o, at + ".type", "type"),
                Subtype = Required(o, at + ".subtype", "subtype"),
                Subtype2 = OptionalString(o, "subtype2", at),
                Bundle = OptionalString(o, "bundle", at),
                Merc = OptionalId(o, "merc", at),
                Item = OptionalId(o, "item", at),
            };
            string problem = RowProblem(row.Type, row.Subtype, row.Subtype2, row.Bundle);
            if (problem != null) throw new Refused(at + ": " + problem);

            // What each category's weight counts (§4.1) must be the row's own reward.
            bool ok;
            switch (row.Category)
            {
                case Avatars:
                    ok = row.Type == "KillSignature" && row.Subtype == "Avatar" && row.Bundle == null;
                    break;
                case Backgrounds:
                    ok = row.Type == "KillSignature" && row.Subtype == "Background" && row.Bundle == null;
                    break;
                case Sounds:
                    ok = row.Type == "KillSignature" && row.Item.HasValue && row.Bundle == SoundBundlePrefix + Text(row.Item.Value);
                    break;
                case Skins:
                    ok = row.Type == "MercSkin" && row.Merc.HasValue && row.Item.HasValue
                         && row.Subtype == Text(row.Merc.Value) && row.Subtype2 == Text(row.Item.Value);
                    break;
                case HiddenJerseys:
                    ok = row.Type == "MercAccessory" && row.Item.HasValue && row.Subtype2 == Text(row.Item.Value);
                    break;
                case Agents:
                    ok = row.Type == "UnlockMerc" && row.Merc.HasValue && row.Subtype == Text(row.Merc.Value);
                    break;
                case Camos:
                    ok = row.Type == "WeaponCamo";
                    break;
                case Jerseys:
                    ok = row.Type == "MercAccessory" && row.Subtype2 == "Random";
                    break;
                case Exhausted:
                    ok = row.Type == "VersusCoins";
                    break;
                default:
                    throw new Refused(at + ": unknown category '" + row.Category + "'");
            }
            if (!ok) throw new Refused(at + ": a " + row.Category + " row cannot be " + row.Type + "/" + row.Subtype + "/" + Describe(row.Subtype2)
                                       + (row.Bundle == null ? "" : " + " + row.Bundle));
            if (row.Bundle != null && row.Category != Sounds) throw new Refused(at + ": only sounds rows carry a bundle");
            return row;
        }

        private static void ReadSeason(CollectorContent c, Dictionary<string, object> season)
        {
            foreach (object t in JsonValue.GetArray(season, "tiers") ?? new List<object>())
            {
                string tier = JsonValue.AsString(t);
                if (string.IsNullOrEmpty(tier)) throw new Refused("season.tiers holds an empty name");
                c.Tiers.Add(tier);
            }
            if (c.Tiers.Count != CollectorOptions.TierCount)
                throw new Refused("season.tiers must name the " + CollectorOptions.TierCount.ToString(CultureInfo.InvariantCulture) + " division tiers");
            foreach (object d in JsonValue.GetArray(season, "divisionTier") ?? new List<object>())
            {
                long? tier = JsonValue.AsLong(d);
                if (!tier.HasValue || tier.Value < 0 || tier.Value >= c.Tiers.Count) throw new Refused("season.divisionTier holds an unknown tier");
                c.DivisionTier.Add((int)tier.Value);
            }
            c.Retarget = CrateGroups(JsonValue.GetArray(season, "retarget"), 2, "season.retarget", c.Tiers.Count);
            c.Placement = CrateGroups(JsonValue.GetArray(season, "placement"), 3, "season.placement", c.Tiers.Count);
            foreach (object e in JsonValue.GetArray(season, "emblems") ?? new List<object>())
            {
                List<int> ids = Ids(e as List<object>, "season.emblems");
                if (ids.Count != 4) throw new Refused("season.emblems: every numeral lists 4 emblems (no star, ★, ★★, ★★★)");
                c.Emblems.Add(ids.ToArray());
            }
            if (c.Emblems.Count == 0) throw new Refused("season.emblems is empty");
        }

        private static List<string[]> CrateGroups(List<object> groups, int size, string name, int tiers)
        {
            if (groups == null || groups.Count != tiers) throw new Refused(name + " must hold one list per tier");
            var result = new List<string[]>();
            foreach (object g in groups)
            {
                var list = g as List<object>;
                if (list == null || list.Count != size) throw new Refused(name + ": every tier lists " + size.ToString(CultureInfo.InvariantCulture) + " crates");
                var crates = new string[size];
                for (int i = 0; i < size; i++)
                {
                    crates[i] = JsonValue.AsString(list[i]);
                    if (string.IsNullOrEmpty(crates[i]) || !(list[i] is string)) throw new Refused(name + " holds an empty crate name");
                }
                result.Add(crates);
            }
            return result;
        }

        /// <summary>The set relations content-gen guarantees and the cells rely on (O5: no Kayac avatar is ever unlocked).</summary>
        private static void Check(CollectorContent c)
        {
            var kayac = new HashSet<int>(c.AvatarsKayac);
            var reserved = new HashSet<int>(c.AvatarsReserved);
            var baseSet = new HashSet<int>(c.AvatarsBase);
            foreach (int a in c.AvatarsBase)
                if (kayac.Contains(a) || reserved.Contains(a)) throw new Refused("avatars.base holds the Kayac or reserved avatar " + Text(a));
            foreach (int a in c.AvatarsDrawable)
                if (kayac.Contains(a) || reserved.Contains(a)) throw new Refused("avatars.drawable holds the Kayac or reserved avatar " + Text(a));
            foreach (int a in c.AvatarsUnlock)
                if (!baseSet.Contains(a)) throw new Refused("avatars.unlock holds " + Text(a) + ", which is not in avatars.base");
            foreach (int a in c.AvatarsLock)
                if (!kayac.Contains(a)) throw new Refused("avatars.lock holds " + Text(a) + ", which is not a Kayac avatar");
            var bgBase = new HashSet<int>(c.BackgroundsBase);
            foreach (int b in c.BackgroundsUnlock)
                if (!bgBase.Contains(b)) throw new Refused("backgrounds.unlock holds " + Text(b) + ", which is not in backgrounds.base");
            foreach (CollectorRow row in c.Rows)
            {
                if (row.Category == Sounds && !c.SoundIds.Contains(row.Item.Value))
                    throw new Refused("row " + Text(row.Id) + ": sound " + Text(row.Item.Value) + " is not in sounds");
                if ((row.Category == Skins || row.Category == Agents) && !c.CamoPools.ContainsKey(row.Merc.Value))
                    throw new Refused("row " + Text(row.Id) + ": agent " + Text(row.Merc.Value) + " is not one of the camos agents");
            }
            foreach (int[] numeral in c.Emblems)
                for (int stars = 1; stars < numeral.Length; stars++)
                    if (baseSet.Contains(numeral[stars])) throw new Refused("the starred season emblem " + Text(numeral[stars]) + " is in avatars.base (D4)");
        }

        // ------------------------------------------------------------------------------------------ helpers

        private static Dictionary<string, object> RequiredObject(Dictionary<string, object> o, string key)
        {
            var value = JsonValue.GetObject(o, key);
            if (value == null) throw new Refused(key + " is missing or not an object");
            return value;
        }

        private static string Required(Dictionary<string, object> o, string path)
        {
            return Required(o, path, path.Substring(path.LastIndexOf('.') + 1));
        }

        private static string Required(Dictionary<string, object> o, string path, string key)
        {
            string value = JsonValue.Get(o, key) as string;
            if (string.IsNullOrEmpty(value)) throw new Refused(path + " is missing or empty");
            return value;
        }

        private static string OptionalString(Dictionary<string, object> o, string key, string at)
        {
            object value;
            if (!o.TryGetValue(key, out value) || value == null) return null;
            string s = value as string;
            // An empty cell value throws in the client's CRMTableCell (§2.3): never send one.
            if (string.IsNullOrEmpty(s)) throw new Refused(at + "." + key + " is not a non-empty string");
            return s;
        }

        private static int? OptionalId(Dictionary<string, object> o, string key, string at)
        {
            object value;
            if (!o.TryGetValue(key, out value) || value == null) return null;
            if (!(value is long) || (long)value < 0 || (long)value > Num.IntMax) throw new Refused(at + "." + key + " is not an id");
            return (int)(long)value;
        }

        private static List<int> Ranges(Dictionary<string, object> o, string key, string where)
        {
            List<int> ids = ExpandRanges(JsonValue.Get(o, key) as string);
            if (ids == null) throw new Refused(where + "." + key + " is missing or not a list of id ranges");
            return ids;
        }

        private static List<int> Ids(List<object> values, string name)
        {
            if (values == null) throw new Refused(name + " is missing or not a list");
            var ids = new List<int>();
            foreach (object v in values)
            {
                if (!(v is long) || (long)v < 0 || (long)v > Num.IntMax) throw new Refused(name + " holds something other than an id");
                ids.Add((int)(long)v);
            }
            return ids;
        }

        private static bool TryId(string text, out int id)
        {
            id = 0;
            if (!IsDigits(text) || text.Length > 9 || (text.Length > 1 && text[0] == '0')) return false;
            foreach (char ch in text) id = id * 10 + (ch - '0');
            return true;
        }

        private static bool IsDigits(string text)
        {
            if (string.IsNullOrEmpty(text)) return false;
            foreach (char ch in text)
                if (ch < '0' || ch > '9') return false;
            return true;
        }

        private static string Describe(string value)
        {
            return value ?? "-";
        }

        private static string Text(int value)
        {
            return value.ToString(CultureInfo.InvariantCulture);
        }

        /// <summary>Why the file is refused (internal control flow of <see cref="Parse(string, out string)"/>).</summary>
        private sealed class Refused : Exception
        {
            public Refused(string message) : base(message)
            {
            }
        }
    }
