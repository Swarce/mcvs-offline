using System;
using System.Collections.Generic;
using McvsOffline.Server.Core;
using McvsOffline.Server.Core.Json;

namespace McvsOffline.Server.Services.Social.LiveOps
{
    /// <summary>A reward as the TLE templates carry it (<c>{"item","quantity"}</c>, TimeLimitedEvent.ParseRewardList).</summary>
    public sealed class LiveOpsReward
    {
        public string Item;
        public int Quantity;
    }

    /// <summary>A quest/achievement objective: one MainTracker with its progression titles and goals.</summary>
    public sealed class LiveOpsObjective
    {
        public string Id;
        public string Tracker;
        public string Title;
        public string TitlePlural;
        public string ThemeTitle;
        public string ThemeDescription;
        public List<int> DailyGoals;
        public List<LiveOpsReward> DailyRewards;
        public List<int> WeeklyGoals;
    }

    /// <summary>A batch of CRM <c>_OverrideTables</c> MUL cells.</summary>
    public sealed class LiveOpsCells
    {
        public string Database;
        public string Table;
        public string Index;
        public List<string> Ids = new List<string>();
        public List<string> Fields = new List<string>();
        public double Factor;
    }

    public sealed class LiveOpsModifier
    {
        public string Id;
        public double RivalFactor = 1.0;
        public List<LiveOpsCells> Cells = new List<LiveOpsCells>();
    }

    /// <summary>
    /// server/Content/liveops.json (generated by tools/content-gen from liveops_tuning.json): our tuning plus the
    /// validated ids. Missing or broken content yields an empty catalogue (no events, logged), never an exception.
    /// </summary>
    public sealed class LiveOpsCatalog
    {
        public const string ContentName = "liveops.json";

        public int Revision = 1;
        public string WeeklyBanner = "", WeeklyMenu = "", DailyBanner = "", DailyMenu = "";

        // Seasons
        public string SeasonTitle = "menu.DivisionTitle";
        public string SeasonDescription = "";
        public List<int> Divisions = new List<int>();
        public List<double> PromotionMatchesPerDay = new List<double>();
        public double TopFactor = 2.2;
        public double SafeFraction = 0.15;
        public int MasterTopRank = 10;
        public int DefaultLevel = 10;
        public int FallbackPromotionZone = 20;
        public int FallbackDemotionZone = 10;

        public List<LiveOpsObjective> Objectives = new List<LiveOpsObjective>();

        // Daily quests
        public string DailyTitle = "", DailyDescription = "", DailyAdvertisement = "", DailyBonusTitle = "";
        public int DailyCount;
        public List<LiveOpsReward> DailyBonusRewards = new List<LiveOpsReward>();

        // Weekly events
        public string WeeklyAdvertisement = "", WeeklyBoostedTag = "", WeeklyFinalTitle = "";
        public int WeeklyCount;
        public List<string> WeeklyThemes = new List<string>();
        public List<List<LiveOpsReward>> WeeklyMilestoneRewards = new List<List<LiveOpsReward>>();
        public List<string> EventCrates = new List<string>();
        public List<LiveOpsReward> WeeklyFinalRewards = new List<LiveOpsReward>();
        public bool WeeklyFinalEventCrate;

        public List<string> Rotation = new List<string>();
        public List<LiveOpsModifier> Modifiers = new List<LiveOpsModifier>();

        public LiveOpsCells SeasonRewards;

        /// <summary>The source text's hash: part of every event revision and of the CRM cache key.</summary>
        public string Hash = "";

        public bool IsEmpty { get { return Divisions.Count == 0 && Objectives.Count == 0; } }

        public LiveOpsObjective Objective(string id)
        {
            foreach (LiveOpsObjective o in Objectives)
                if (string.Equals(o.Id, id, StringComparison.Ordinal)) return o;
            return null;
        }

        public LiveOpsModifier Modifier(string id)
        {
            foreach (LiveOpsModifier m in Modifiers)
                if (string.Equals(m.Id, id, StringComparison.OrdinalIgnoreCase)) return m;
            return null;
        }

        public double PromotionMatches(int division)
        {
            int i = Divisions.IndexOf(division);
            if (i < 0 || i >= PromotionMatchesPerDay.Count) return PromotionMatchesPerDay.Count > 0 ? PromotionMatchesPerDay[PromotionMatchesPerDay.Count - 1] : 5.0;
            return PromotionMatchesPerDay[i];
        }

        public static LiveOpsCatalog Parse(string text, Log log)
        {
            var c = new LiveOpsCatalog();
            object parsed;
            if (string.IsNullOrEmpty(text) || !MiniJson.TryParse(text, out parsed) || !(parsed is Dictionary<string, object>))
            {
                if (log != null) log.Error(ContentName + " is missing or not a JSON object: live ops are off");
                return c;
            }
            var root = (Dictionary<string, object>)parsed;
            c.Hash = LiveOpsHash.Hex(text);
            try
            {
                c.Revision = (int)Num.Clamp(JsonValue.GetLong(root, "revision", 1), 0, 100000);
                var images = JsonValue.GetObject(root, "images");
                c.WeeklyBanner = JsonValue.GetString(images, "weeklyBanner", "") ?? "";
                c.WeeklyMenu = JsonValue.GetString(images, "weeklyMenu", "") ?? "";
                c.DailyBanner = JsonValue.GetString(images, "dailyBanner", "") ?? "";
                c.DailyMenu = JsonValue.GetString(images, "dailyMenu", "") ?? "";

                var seasons = JsonValue.GetObject(root, "seasons");
                c.SeasonTitle = JsonValue.GetString(seasons, "title", c.SeasonTitle) ?? c.SeasonTitle;
                c.SeasonDescription = JsonValue.GetString(seasons, "description", "") ?? "";
                foreach (object d in JsonValue.GetArray(seasons, "divisions") ?? new List<object>())
                {
                    long? id = JsonValue.AsLong(d);
                    if (id.HasValue && id.Value >= 1 && id.Value <= 99) c.Divisions.Add((int)id.Value);
                }
                foreach (object m in JsonValue.GetArray(seasons, "promotionMatchesPerDay") ?? new List<object>())
                    c.PromotionMatchesPerDay.Add(Positive(JsonValue.AsDouble(m), 5.0));
                c.TopFactor = Positive(JsonValue.AsDouble(JsonValue.Get(seasons, "topFactor")), 2.2);
                c.SafeFraction = Positive(JsonValue.AsDouble(JsonValue.Get(seasons, "safeFraction")), 0.15);
                c.MasterTopRank = (int)Num.Clamp(JsonValue.GetLong(seasons, "masterTopRank", 10), 1, 1000);
                c.DefaultLevel = (int)Num.Clamp(JsonValue.GetLong(seasons, "defaultLevel", 10), 1, 1000);
                var zones = JsonValue.GetObject(seasons, "fallbackZones");
                c.FallbackPromotionZone = (int)Num.Clamp(JsonValue.GetLong(zones, "promotion", 20), 0, 100);
                c.FallbackDemotionZone = (int)Num.Clamp(JsonValue.GetLong(zones, "demotion", 10), 0, 100);

                foreach (object item in JsonValue.GetArray(root, "objectives") ?? new List<object>())
                {
                    var o = item as Dictionary<string, object>;
                    if (o == null) continue;
                    var objective = new LiveOpsObjective
                    {
                        Id = JsonValue.GetString(o, "id"),
                        Tracker = JsonValue.GetString(o, "tracker"),
                        Title = JsonValue.GetString(o, "title"),
                        TitlePlural = JsonValue.GetString(o, "titlePlural"),
                    };
                    if (string.IsNullOrEmpty(objective.Id) || string.IsNullOrEmpty(objective.Tracker) || string.IsNullOrEmpty(objective.Title))
                        continue;
                    if (string.IsNullOrEmpty(objective.TitlePlural)) objective.TitlePlural = objective.Title;
                    var theme = JsonValue.GetObject(o, "theme");
                    if (theme != null)
                    {
                        objective.ThemeTitle = JsonValue.GetString(theme, "title");
                        objective.ThemeDescription = JsonValue.GetString(theme, "description") ?? "";
                    }
                    var daily = JsonValue.GetObject(o, "daily");
                    if (daily != null)
                    {
                        objective.DailyGoals = Goals(JsonValue.GetArray(daily, "goals"));
                        objective.DailyRewards = Rewards(JsonValue.GetArray(daily, "rewards"));
                        if (objective.DailyGoals.Count == 0 || objective.DailyRewards.Count == 0)
                        {
                            objective.DailyGoals = null;
                            objective.DailyRewards = null;
                        }
                    }
                    var weekly = JsonValue.GetObject(o, "weekly");
                    if (weekly != null)
                    {
                        objective.WeeklyGoals = Goals(JsonValue.GetArray(weekly, "goals"));
                        if (objective.WeeklyGoals.Count == 0) objective.WeeklyGoals = null;
                    }
                    c.Objectives.Add(objective);
                }

                var dq = JsonValue.GetObject(root, "dailyQuests");
                c.DailyTitle = JsonValue.GetString(dq, "title", "") ?? "";
                c.DailyDescription = JsonValue.GetString(dq, "description", "") ?? "";
                c.DailyAdvertisement = JsonValue.GetString(dq, "advertisement", "") ?? "";
                c.DailyCount = (int)Num.Clamp(JsonValue.GetLong(dq, "count", 3), 0, 10);
                var bonus = JsonValue.GetObject(dq, "bonus");
                c.DailyBonusTitle = JsonValue.GetString(bonus, "title", "") ?? "";
                c.DailyBonusRewards = Rewards(JsonValue.GetArray(bonus, "rewards"));

                var we = JsonValue.GetObject(root, "weeklyEvents");
                c.WeeklyAdvertisement = JsonValue.GetString(we, "advertisement", "") ?? "";
                c.WeeklyBoostedTag = JsonValue.GetString(we, "boostedTag", "") ?? "";
                c.WeeklyCount = (int)Num.Clamp(JsonValue.GetLong(we, "count", 4), 0, 10);
                foreach (object t in JsonValue.GetArray(we, "themes") ?? new List<object>())
                {
                    string theme = JsonValue.AsString(t);
                    if (!string.IsNullOrEmpty(theme)) c.WeeklyThemes.Add(theme);
                }
                foreach (object tier in JsonValue.GetArray(we, "milestoneRewards") ?? new List<object>())
                    c.WeeklyMilestoneRewards.Add(Rewards(JsonValue.AsArray(tier)));
                foreach (object crate in JsonValue.GetArray(we, "eventCrates") ?? new List<object>())
                {
                    string id = JsonValue.AsString(crate);
                    if (!string.IsNullOrEmpty(id)) c.EventCrates.Add(id);
                }
                var final = JsonValue.GetObject(we, "final");
                c.WeeklyFinalTitle = JsonValue.GetString(final, "title", "") ?? "";
                c.WeeklyFinalRewards = Rewards(JsonValue.GetArray(final, "rewards"));
                c.WeeklyFinalEventCrate = JsonValue.GetBool(final, "eventCrate", false);

                var modifiers = JsonValue.GetObject(root, "modifiers");
                foreach (object r in JsonValue.GetArray(modifiers, "rotation") ?? new List<object>())
                {
                    string id = JsonValue.AsString(r);
                    if (!string.IsNullOrEmpty(id)) c.Rotation.Add(id);
                }
                foreach (object item in JsonValue.GetArray(modifiers, "definitions") ?? new List<object>())
                {
                    var m = item as Dictionary<string, object>;
                    string id = JsonValue.GetString(m, "id");
                    if (string.IsNullOrEmpty(id)) continue;
                    var modifier = new LiveOpsModifier { Id = id, RivalFactor = Positive(JsonValue.AsDouble(JsonValue.Get(m, "rivalFactor")), 1.0) };
                    foreach (object cell in JsonValue.GetArray(m, "cells") ?? new List<object>())
                    {
                        LiveOpsCells cells = Cells(cell as Dictionary<string, object>, JsonValue.AsDouble(JsonValue.Get(cell as Dictionary<string, object>, "factor")));
                        if (cells != null) modifier.Cells.Add(cells);
                    }
                    c.Modifiers.Add(modifier);
                }
                c.SeasonRewards = Cells(JsonValue.GetObject(root, "seasonRewards"), 1.0);
            }
            catch (Exception ex)
            {
                if (log != null) log.Error(ContentName + " could not be read: live ops are off", ex);
                return new LiveOpsCatalog();
            }
            return c;
        }

        private static LiveOpsCells Cells(Dictionary<string, object> o, double? factor)
        {
            if (o == null) return null;
            var cells = new LiveOpsCells
            {
                Database = JsonValue.GetString(o, "database"),
                Table = JsonValue.GetString(o, "table"),
                Index = JsonValue.GetString(o, "index"),
                Factor = Positive(factor, 1.0),
            };
            foreach (object id in JsonValue.GetArray(o, "ids") ?? new List<object>())
            {
                string s = JsonValue.AsString(id);
                if (!string.IsNullOrEmpty(s)) cells.Ids.Add(s);
            }
            foreach (object f in JsonValue.GetArray(o, "fields") ?? new List<object>())
            {
                string s = JsonValue.AsString(f);
                if (!string.IsNullOrEmpty(s)) cells.Fields.Add(s);
            }
            if (string.IsNullOrEmpty(cells.Database) || string.IsNullOrEmpty(cells.Table) || string.IsNullOrEmpty(cells.Index)
                || cells.Ids.Count == 0 || cells.Fields.Count == 0)
                return null;
            return cells;
        }

        private static List<int> Goals(List<object> values)
        {
            var goals = new List<int>();
            foreach (object v in values ?? new List<object>())
            {
                long? g = JsonValue.AsLong(v);
                if (g.HasValue && g.Value > 0 && g.Value < 1000000) goals.Add((int)g.Value);
            }
            return goals;
        }

        private static List<LiveOpsReward> Rewards(List<object> values)
        {
            var rewards = new List<LiveOpsReward>();
            foreach (object v in values ?? new List<object>())
            {
                var r = v as Dictionary<string, object>;
                string item = JsonValue.GetString(r, "item");
                long quantity = JsonValue.GetLong(r, "quantity", 0);
                if (string.IsNullOrEmpty(item) || quantity <= 0 || quantity > 1000000) continue;
                rewards.Add(new LiveOpsReward { Item = item, Quantity = (int)quantity });
            }
            return rewards;
        }

        private static double Positive(double? value, double fallback)
        {
            return value.HasValue && value.Value > 0 && !double.IsNaN(value.Value) && !double.IsInfinity(value.Value) ? value.Value : fallback;
        }
    }

    /// <summary>FNV-1a hashes and a deterministic xorshift generator: stable across runtimes (unlike
    /// <c>string.GetHashCode</c> or <c>System.Random</c>).</summary>
    public static class LiveOpsHash
    {
        public static ulong Fnv64(string text)
        {
            ulong hash = 14695981039346656037UL;
            foreach (byte b in System.Text.Encoding.UTF8.GetBytes(text ?? ""))
            {
                hash ^= b;
                hash *= 1099511628211UL;
            }
            return hash == 0 ? 0x9E3779B97F4A7C15UL : hash;
        }

        public static string Hex(string text)
        {
            return Fnv64(text).ToString("x16", System.Globalization.CultureInfo.InvariantCulture);
        }

        /// <summary>A positive 31-bit value (an event <c>_version</c>; the TS reads it with Convert.ToInt32).</summary>
        public static int Revision(string text)
        {
            int value = (int)(Fnv64(text) & 0x7FFFFFFFUL);
            return value == 0 ? 1 : value;
        }

        public static ulong Next(ref ulong state)
        {
            state ^= state >> 12;
            state ^= state << 25;
            state ^= state >> 27;
            return state * 2685821657736338717UL;
        }

        public static double Unit(ref ulong state)
        {
            return (Next(ref state) >> 11) * (1.0 / 9007199254740992.0);
        }

        /// <summary>0 &lt;= result &lt; n.</summary>
        public static int Below(ref ulong state, int n)
        {
            return n <= 1 ? 0 : (int)(Next(ref state) % (ulong)n);
        }
    }
