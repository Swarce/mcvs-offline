using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;

namespace McvsOffline.Tools.HdTextures
{
    /// <summary>A level of the game and the "MapNN" folder name its art uses (Port = Map01).</summary>
    internal sealed class HdLevel
    {
        public string Name { get; set; }
        public string Alias { get; set; }
    }

    /// <summary>One texture the converter can replace: our own facts about it, no game data.</summary>
    internal sealed class HdIndexEntry
    {
        /// <summary>CRC-32 of the logical path, 8 lower-case hex digits.</summary>
        public string Hash { get; set; }
        public string Category { get; set; }
        public string[] Levels { get; set; } = new string[0];

        /// <summary><c>ktx</c> (GCBF-wrapped KTX) or <c>split</c> (split-alpha zip) on Android.</summary>
        public string Layout { get; set; }
        public long AndroidSize { get; set; }
        public int AndroidWidth { get; set; }
        public int AndroidHeight { get; set; }
        public int AndroidMips { get; set; }
        public long PcSize { get; set; }
        public int PcWidth { get; set; }
        public int PcHeight { get; set; }
        public int PcMips { get; set; }

        public uint Crc => uint.Parse(Hash, NumberStyles.HexNumber, CultureInfo.InvariantCulture);

        /// <summary>The Android file under <c>Data/</c>: "1/9921a.f" (hex, unpadded, first digit as folder).</summary>
        public string AndroidPath
        {
            get
            {
                string hex = Crc.ToString("x", CultureInfo.InvariantCulture);
                return hex.Substring(0, 1) + "/" + hex.Substring(1) + ".f";
            }
        }

        /// <summary>The PC file under <c>Data/</c>: "1675802.f" (decimal).</summary>
        public string PcPath => Crc.ToString(CultureInfo.InvariantCulture) + ".f";

        /// <summary>Files that go in and out together: every lightmap of a level.</summary>
        public string Group => Category == HdIndex.Lightmaps && Levels.Length == 1 ? "lightmaps:" + Levels[0] : null;

        /// <summary>Texels of the PC size over the levels the output gets (the Android count plus one per doubling).</summary>
        public long OutputTexels
        {
            get
            {
                long sum = 0;
                int levels = AndroidMips + Doublings;
                for (int i = 0; i < levels; i++) sum += (long)Ktx.MipSize(PcWidth, i) * Ktx.MipSize(PcHeight, i);
                return Layout == "split" ? 2 * sum : sum;
            }
        }

        public int Doublings
        {
            get
            {
                int k = 0;
                while ((AndroidWidth << k) < PcWidth) k++;
                return k;
            }
        }
    }

    /// <summary>
    /// The table of convertible textures (<c>hd-index.tsv</c>, embedded): hash, category, levels, Android layout and sizes, PC
    /// sizes. Generated by the maintainer command <c>index</c> (<see cref="IndexBuilder"/>) from a data pack and a PC install;
    /// it holds no game data (no names, no content). Format: '#' comments, then tab-separated rows
    /// <c>level &lt;name&gt; &lt;alias|-&gt;</c> and
    /// <c>tex &lt;hash&gt; &lt;category&gt; &lt;levels|-&gt; &lt;layout&gt; &lt;androidSize&gt; &lt;w&gt; &lt;h&gt; &lt;mips&gt; &lt;pcSize&gt; &lt;w&gt; &lt;h&gt; &lt;mips&gt;</c>.
    /// </summary>
    internal sealed class HdIndex
    {
        public const string Surfaces = "surfaces";
        public const string Lightmaps = "lightmaps";
        public const string Characters = "characters";
        public const string Equipment = "equipment";
        public const string Props = "props";
        public const string Vfx = "vfx";
        public const string Menus3d = "menus3d";
        public const string Minimaps = "minimaps";

        public const string ResourceName = "hd-index.tsv";
        public const string GameVersion = "1.17.32";
        public const string Pack = "ETC";

        /// <summary>The default scope: research pc-textures.md §7 tiers 1 and 2.</summary>
        public static readonly string[] DefaultCategories = { Surfaces, Lightmaps, Characters, Equipment };

        /// <summary>Every category, in the table's order.</summary>
        public static readonly string[] AllCategories = { Surfaces, Lightmaps, Characters, Equipment, Props, Vfx, Menus3d, Minimaps };

        public List<HdLevel> Levels { get; } = new List<HdLevel>();
        public List<HdIndexEntry> Entries { get; } = new List<HdIndexEntry>();

        public static HdIndex Load()
        {
            Assembly assembly = typeof(HdIndex).Assembly;
            using (Stream s = assembly.GetManifestResourceStream(ResourceName))
            {
                if (s == null) throw new InvalidDataException("the texture table " + ResourceName + " is missing from the tool");
                using (var reader = new StreamReader(s, Encoding.UTF8))
                    return Parse(reader.ReadToEnd());
            }
        }

        public static HdIndex Parse(string text)
        {
            var index = new HdIndex();
            int lineNumber = 0;
            foreach (string raw in text.Split('\n'))
            {
                lineNumber++;
                string line = raw.TrimEnd('\r');
                if (line.Length == 0 || line[0] == '#') continue;
                string[] f = line.Split('\t');
                try
                {
                    if (f[0] == "level" && f.Length == 3)
                    {
                        index.Levels.Add(new HdLevel { Name = f[1], Alias = f[2] == "-" ? null : f[2] });
                    }
                    else if (f[0] == "tex" && f.Length == 13)
                    {
                        index.Entries.Add(new HdIndexEntry
                        {
                            Hash = f[1], Category = f[2], Levels = f[3] == "-" ? new string[0] : f[3].Split(','), Layout = f[4],
                            AndroidSize = long.Parse(f[5], CultureInfo.InvariantCulture), AndroidWidth = Int(f[6]), AndroidHeight = Int(f[7]), AndroidMips = Int(f[8]),
                            PcSize = long.Parse(f[9], CultureInfo.InvariantCulture), PcWidth = Int(f[10]), PcHeight = Int(f[11]), PcMips = Int(f[12]),
                        });
                    }
                    else
                    {
                        throw new FormatException("unknown row");
                    }
                }
                catch (FormatException ex)
                {
                    throw new InvalidDataException("texture table line " + lineNumber + ": " + ex.Message);
                }
            }
            return index;
        }

        public string Write(IEnumerable<string> header)
        {
            var sb = new StringBuilder();
            foreach (string h in header) sb.Append("# ").Append(h).Append('\n');
            foreach (HdLevel l in Levels) sb.Append("level\t").Append(l.Name).Append('\t').Append(l.Alias ?? "-").Append('\n');
            foreach (HdIndexEntry e in Entries)
            {
                sb.Append(string.Join("\t", new[]
                {
                    "tex", e.Hash, e.Category, e.Levels.Length == 0 ? "-" : string.Join(",", e.Levels), e.Layout,
                    S(e.AndroidSize), S(e.AndroidWidth), S(e.AndroidHeight), S(e.AndroidMips), S(e.PcSize), S(e.PcWidth), S(e.PcHeight), S(e.PcMips),
                })).Append('\n');
            }
            return sb.ToString();
        }

        /// <summary>Parses "default", "all" or a comma list of categories.</summary>
        public static string[] ParseScope(string scope)
        {
            if (string.IsNullOrWhiteSpace(scope) || scope.Equals("default", StringComparison.OrdinalIgnoreCase)) return DefaultCategories;
            if (scope.Equals("all", StringComparison.OrdinalIgnoreCase)) return AllCategories;
            var chosen = new List<string>();
            foreach (string part in scope.Split(new[] { ',', '+', ' ' }, StringSplitOptions.RemoveEmptyEntries))
            {
                string c = AllCategories.FirstOrDefault(a => a.Equals(part.Trim(), StringComparison.OrdinalIgnoreCase));
                if (c == null) throw new ArgumentException("unknown category '" + part + "' (known: " + string.Join(", ", AllCategories) + ", or default, all)");
                if (!chosen.Contains(c)) chosen.Add(c);
            }
            return AllCategories.Where(chosen.Contains).ToArray();
        }

        /// <summary>The scope's name in file names and the manifest: "default", "all" or the categories joined by '+'.</summary>
        public static string ScopeName(string[] categories)
        {
            if (categories.SequenceEqual(DefaultCategories)) return "default";
            if (categories.SequenceEqual(AllCategories)) return "all";
            return string.Join("+", categories);
        }

        /// <summary>Level names from "all" (null) or a comma list of names or aliases (Port, map01).</summary>
        public string[] ParseMaps(string maps)
        {
            if (string.IsNullOrWhiteSpace(maps) || maps.Equals("all", StringComparison.OrdinalIgnoreCase)) return null;
            var chosen = new List<string>();
            foreach (string part in maps.Split(new[] { ',', '+', ' ' }, StringSplitOptions.RemoveEmptyEntries))
            {
                string p = part.Trim();
                HdLevel level = Levels.FirstOrDefault(l => l.Name.Equals(p, StringComparison.OrdinalIgnoreCase) ||
                                                           (l.Alias != null && l.Alias.Equals(p, StringComparison.OrdinalIgnoreCase)));
                if (level == null)
                    throw new ArgumentException("unknown map '" + p + "' (known: " + string.Join(", ", Levels.Select(l => l.Alias == null ? l.Name : l.Name + " = " + l.Alias)) + ")");
                if (!chosen.Contains(level.Name)) chosen.Add(level.Name);
            }
            return Levels.Select(l => l.Name).Where(chosen.Contains).ToArray();
        }

        /// <summary>
        /// The entries of the chosen categories. With <paramref name="maps"/> (null = all levels), surfaces are taken when one
        /// of their levels is chosen, lightmaps and minimaps when their level is; the other categories do not depend on a level.
        /// </summary>
        public List<HdIndexEntry> Select(string[] categories, string[] maps)
        {
            var result = new List<HdIndexEntry>();
            foreach (HdIndexEntry e in Entries)
            {
                if (!categories.Contains(e.Category)) continue;
                if (maps != null && (e.Category == Surfaces || e.Category == Lightmaps || e.Category == Minimaps) && !e.Levels.Any(maps.Contains)) continue;
                result.Add(e);
            }
            return result;
        }

        /// <summary>
        /// The category of a logical path and, for lightmaps and minimaps, its level; null for what is never converted (UI,
        /// first-person weapons and arms, IBL cubemaps, anything else).
        /// </summary>
        public static string Categorize(string logicalPath, out string level)
        {
            level = null;
            string p = logicalPath.Replace('\\', '/');
            string[] parts = p.Split('/');
            if (p.StartsWith("Baked/Levels/", StringComparison.Ordinal) && parts.Length == 4)
            {
                string l = parts[2];
                if (IsLightmapName(parts[3], l))
                {
                    level = l;
                    return Lightmaps;
                }
                return null;
            }
            if (p.StartsWith("Levels/", StringComparison.Ordinal) && parts.Length == 3 && parts[2].IndexOf(".minimap", StringComparison.OrdinalIgnoreCase) >= 0)
            {
                level = parts[1];
                return Minimaps;
            }
            if (p.StartsWith("3d/Environment/", StringComparison.Ordinal)) return Surfaces;
            if (p.StartsWith("3d/Characters/", StringComparison.Ordinal))
                return parts.Any(s => s.Equals("FP", StringComparison.OrdinalIgnoreCase)) ? null : Characters;
            if (p.StartsWith("3d/Equipment/", StringComparison.Ordinal)) return Equipment;
            if (p.StartsWith("3d/Objects/", StringComparison.Ordinal) || p.StartsWith("3d/Vehicles/", StringComparison.Ordinal) ||
                p.StartsWith("3d/Maps/", StringComparison.Ordinal)) return Props;
            if (p.StartsWith("3d/VFX/", StringComparison.Ordinal)) return Vfx;
            if (p.StartsWith("3d/Menus/", StringComparison.Ordinal) || p.StartsWith("3d/Menu/", StringComparison.Ordinal)) return Menus3d;
            return null;
        }

        /// <summary>"Port.Lightmap_0.tga", "Port.Lightmap_0.dirirr.tga", "Port.Lightmap_0.lowend.tga" for level Port.</summary>
        public static bool IsLightmapName(string fileName, string level)
        {
            string prefix = level + ".Lightmap_";
            if (!fileName.StartsWith(prefix, StringComparison.Ordinal)) return false;
            string rest = fileName.Substring(prefix.Length);
            int digits = 0;
            while (digits < rest.Length && char.IsDigit(rest[digits])) digits++;
            if (digits == 0) return false;
            string suffix = rest.Substring(digits);
            return suffix == ".tga" || suffix == ".dirirr.tga" || suffix == ".lowend.tga";
        }

        /// <summary>The logical paths a level's lightmaps can have (for naming them in the manifest).</summary>
        public static IEnumerable<string> LightmapCandidates(string level)
        {
            for (int n = 0; n < 64; n++)
            {
                foreach (string suffix in new[] { ".tga", ".dirirr.tga", ".lowend.tga" })
                    yield return "Baked/Levels/" + level + "/" + level + ".Lightmap_" + n.ToString(CultureInfo.InvariantCulture) + suffix;
            }
        }

        private static int Int(string s) => int.Parse(s, CultureInfo.InvariantCulture);

        private static string S(long v) => v.ToString(CultureInfo.InvariantCulture);
    }
}
